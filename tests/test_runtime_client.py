"""Data-plane invoke client tests (src/delphi/agent/runtime_client.py).

Verifies the eval driver calls the CURRENT AgentCore data-plane API
(invoke_agent_runtime on the bedrock-agentcore service) with the right shape, using a
fake boto3 client so no live runtime is needed.
"""
from __future__ import annotations

import io
import json

from delphi.agent.runtime_client import AgentCoreRuntimeInvoker


class FakeAgentCoreClient:
    def __init__(self):
        self.calls = []

    def invoke_agent_runtime(self, **kwargs):
        self.calls.append(kwargs)
        body = json.dumps({"chosen_model": "nova-lite", "output": "4"}).encode()
        return {
            "response": io.BytesIO(body),
            "statusCode": 200,
            "runtimeSessionId": kwargs["runtimeSessionId"],
        }


def test_invoke_uses_agentcore_dataplane_contract():
    fake = FakeAgentCoreClient()
    invoker = AgentCoreRuntimeInvoker("arn:aws:bedrock-agentcore:...:runtime/abc", client=fake)
    resp = invoker.invoke("what is 2+2?", session_id="sess-1")

    assert resp.status_code == 200
    assert resp.payload["chosen_model"] == "nova-lite"
    assert resp.session_id == "sess-1"

    (call,) = fake.calls
    assert call["agentRuntimeArn"].endswith("runtime/abc")
    assert call["runtimeSessionId"] == "sess-1"
    # payload is JSON bytes carrying the prompt
    assert json.loads(call["payload"])["prompt"] == "what is 2+2?"
    assert call["contentType"] == "application/json"


def test_qualifier_is_forwarded_when_set():
    fake = FakeAgentCoreClient()
    invoker = AgentCoreRuntimeInvoker("arn:...:runtime/abc", client=fake, qualifier="prod")
    invoker.invoke("hi", session_id="s")
    assert fake.calls[0]["qualifier"] == "prod"


def test_session_id_autogenerated_when_absent():
    fake = FakeAgentCoreClient()
    invoker = AgentCoreRuntimeInvoker("arn:...:runtime/abc", client=fake)
    resp = invoker.invoke("hi")
    assert resp.session_id  # non-empty auto id
    assert fake.calls[0]["runtimeSessionId"] == resp.session_id


def test_autogenerated_session_id_meets_the_service_minimum_length():
    """Found by deployment, not by the suite: the first live `delphi-verify` run failed
    client-side with `ParamValidationError: Invalid length for parameter runtimeSessionId,
    value: 32, valid min length: 33`. `uuid4().hex` is exactly 32 characters, and the
    fake above accepts any non-empty id, so nothing here could catch it.

    Asserted against the botocore service model, not a literal, so the test tracks the
    real constraint rather than our memory of it.
    """
    import botocore.session

    model = botocore.session.get_session().get_service_model("bedrock-agentcore")
    shape = model.operation_model("InvokeAgentRuntime").input_shape
    minimum = shape.members["runtimeSessionId"].metadata["min"]

    fake = FakeAgentCoreClient()
    invoker = AgentCoreRuntimeInvoker("arn:...:runtime/abc", client=fake)
    for _ in range(20):
        invoker.invoke("hi")
    assert all(len(c["runtimeSessionId"]) >= minimum for c in fake.calls), minimum
